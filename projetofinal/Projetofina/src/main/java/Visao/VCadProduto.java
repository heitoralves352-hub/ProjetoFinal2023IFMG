     private void setStatusRegistro(int status){
        StatusRegistro = status;
        habilitarBotoes();
        
        if (status == INSERCAO || status == FECHADO){
            limparCampos();
        }
        
    }
     private void habilitarBotoes(){
        boolean habilitar = (StatusRegistro == ABERTO || StatusRegistro == FECHADO);
        
        btnIncluir.setEnabled(habilitar);
        btnExcluir.setEnabled(habilitar);
        btnSalvar.setEnabled(!habilitar);
        btnCancel.setEnabled(!habilitar);
        btnPesq.setEnabled(habilitar);
        txtcod.setEnabled(habilitar);
        
        Component[] c= pnnavegação.getComponents();
        for (int i = 0; i < c.length; i++) {
            c[i].setEnabled(habilitar);
        }
    }
    
    
    private void limparCampos(){
        txtcod.setText("0");
        txtNome.setText("");
        txtPesq.setText("");
        txtEstoque.setText("");
        txtpreco.setText("");
        
    }
    
    private void PreencherTelaComObjetoRecuperado(ArrayList<String> Registro){
        if(!Registro.get(0).equals("-1")){
            txtcod.setText(Registro.get(0));
            txtNome.setText(Registro.get(1));
            //txtPesq.setText(Registro.get(2));
            txtEstoque.setText(Registro.get(3));
            txtpreco.setText(Registro.get(4));
            txtPesq.setText(Registro.get(5));
            txtResul.setText(Registro.get(2));
        }
    }

