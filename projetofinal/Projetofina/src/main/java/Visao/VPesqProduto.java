    private void btnPesqActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesqActionPerformed
        ArrayList<String> Parametros = new ArrayList<>();
        Parametros.add(cmbopcao.getSelectedItem().toString());
        Parametros.add(txtConteudo.getText().toUpperCase());
        
        Vector<String> vColunas = new Vector<>();
        vColunas = PegaColunasDaGrade();
        
        DefaultTableModel objTabela = new DefaultTableModel(vColunas, 0);
        
        ctrlProduto ControllerProduto = new ctrlProduto();
        objTabela = ControllerProduto.PesquisaObjeto(Parametros, objTabela);
        
        tblresultados.setModel(objTabela);
    }//GEN-LAST:event_btnPesqActionPerformed

    private void btnConfActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfActionPerformed
        int linha = tblresultados.getSelectedRow();
       
        if (linha == -1){
            JOptionPane.showMessageDialog(rootPane, "Selecione o registro desejado.");
        } else {
            int Codigo = Integer.valueOf(tblresultados.getValueAt(linha, 0).toString());
            this.TelaPai.setRetornoConsulta(Codigo);
            this.setVisible(false);
            this.dispose();
        }
    }//GEN-LAST:event_btnConfActionPerformed

