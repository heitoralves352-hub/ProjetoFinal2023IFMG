    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
         ArrayList<String> Registro =new ArrayList<>();
        Registro.add(txtCod.getText());
        Registro.add(txtnome.getText());
        Registro.add(txtdesc.getText());
        
        int codigoNovo = 0;
        ctrlCategoria ControllerCategoria = new ctrlCategoria();
        
        if (StatusRegistro == INSERCAO){
            codigoNovo= ControllerCategoria.Salvar(Registro);
            txtCod.setText(String.valueOf(codigoNovo));
        }else if(StatusRegistro == EDICAO){
            ControllerCategoria.Atualizar(Registro);

        }
        
        setStatusRegistro(ABERTO);
    }//GEN-LAST:event_btnSalvarActionPerformed

