    private void btnsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsalvarActionPerformed
        ArrayList<String> Registro =new ArrayList<>();
        Registro.add(txtcod.getText());
        Registro.add(txtnome.getText());
        Registro.add(txtEmail.getText());
        Registro.add(txtendereço.getText());
        Registro.add(txtCnpj.getText());
        Registro.add(txttel.getText());

        
        int codigoNovo = 0;
        ctrlFornecedor ControllerFornecedor= new ctrlFornecedor();
        
        if (StatusRegistro == INSERCAO){
            codigoNovo= ControllerFornecedor.Salvar(Registro);
            txtcod.setText(String.valueOf(codigoNovo));
        }else if(StatusRegistro == EDICAO){
            ControllerFornecedor.Atualizar(Registro);
        }
        
        setStatusRegistro(ABERTO);
    }//GEN-LAST:event_btnsalvarActionPerformed

    private void txtcodFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_txtcodFocusLost
       int codigoAtual = Integer.parseInt(txtcod.getText());
        
        if (codigoAtual > 0){
            ctrlFornecedor controllerFornecedor = new ctrlFornecedor();
            ArrayList<String> Registro = controllerFornecedor.RecuperarObjeto(codigoAtual);
            
            if(!Registro.get(0).equals("-1")){
                PreencherTelaComObjetoRecuperado(Registro);
               setStatusRegistro(ABERTO);
            }else{
                JOptionPane.showMessageDialog(rootPane, "Registro não encontrado");
                setStatusRegistro(FECHADO);
            }
        }
    }//GEN-LAST:event_txtcodFocusLost

